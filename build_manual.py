def warn(t): return f'<div class="warn"><b>重要提示：</b>{t}</div>'
def dtable(headers, rows):
    ths = ''.join(f'<th>{h}</th>' for h in headers)
    trs = []
    for row in rows:
        trs.append('<tr>' + ''.join(f'<td>{c}</td>' for c in row) + '</tr>')
    return f'<table class="data"><tr>{ths}</tr>{"".join(trs)}</table>'

